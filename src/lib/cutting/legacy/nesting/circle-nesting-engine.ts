import type { Circle, CutType } from '../types/common.ts';

export interface PostedCircle {
	id: string;
	x: number;
	y: number;
	diameter: number; // Effective diameter used for packing (with kerf)
	originalDiameter: number;
	cutType: CutType;
	name: string;
	depth?: number;
}

export interface CircleSheet {
	width: number;
	height: number;
	circles: PostedCircle[];
	efficiency: number;
}

/**
 * Nests circles using a staggered grid (hexagonal packing) strategy.
 * For circles of equal size, this is optimal.
 * For mixed sizes, we sort by diameter descending and try to place them.
 * A truly optimal mixed-circle packer is complex (finding holes).
 * We will use a "Best Fit Decreasing" approach on top of a candidate coordinate list logic
 * or a simpler "Row by Row" with staggering.
 *
 * Strategy:
 * 1. Sort circles by diameter descending.
 * 2. Maintain a list of sheets.
 * 3. For each circle, try to place in existing sheets, else create new.
 * 4. Placement strategy:
 *    - Try to place at "candidate positions" generated by existing circles.
 *    - For every placed circle C at (x,y), new candidates are at distance (R1+R2+padding) at 60 degree intervals (hexagonal).
 *    - Also keep (0,0) and corners as candidates.
 *    - Choose the candidate with lowest Y, then lowest X (Bottom-Left rule).
 */
export function nestCircles(
	circles: Circle[],
	boardWidth: number,
	boardHeight: number,
	kerf: number,
	padding: number = 0
): CircleSheet[] {
	const gap = Math.max(kerf, padding);

	// Flatten requests into individual items
	const items: PostedCircle[] = [];
	circles.forEach(c => {
		for (let i = 0; i < c.quantity; i++) {
			// Effective diameter heavily depends on cut type?
			// Actually, for nesting, we usually care about the "Stock removal".
			// If it's a hole inside, we still need the full outer diameter space.
			// If it's a profile outside, we need diameter + kerf space.
			// Let's assume Diameter is the finished part size.
			// Space needed = Diameter + Kerf (for outside cut) or Diameter (for inside).
			// To be safe and simple, let's treat diameter as the bounding circle needed + kerf.
			// Actually, if CutType is "Outside", the tool goes outside. So we need (Diameter + Kerf) space.
			// If CutType is "Inside" or "Pocket", the tool stays inside. The outer boundary is Diameter.
			// But we technically need separation between parts.
			// Let's use: PackingDiameter = Diameter + (CutType === 'outside' ? Kerf : 0)

			// Wait, standard practice: User specifies Target Diameter.
			// "Outside" means we want a disc of Diameter D. Tool path is at D + Kerf. Space used is D + Kerf.
			// "Inside" means we want a hole of Diameter D. Tool path is inside. Space used is D.
			// But we need to keep the board integrity? "Inside" means we cut a hole in the board.
			// Usually we still treat the "occupancy" as diameter.

			// For simplicity and safety: Always wrap with gap.
			// Occupied Diameter = Diameter + (CutType === 'outside' ? kerf : 0).
			const occupiedDiameter =
				c.diameter + (c.cutType === 'outside' ? kerf : 0);

			items.push({
				id: `${c.id}_${i}`,
				x: 0,
				y: 0,
				diameter: occupiedDiameter,
				originalDiameter: c.diameter,
				cutType: c.cutType,
				name: c.name,
                depth: c.depth,
			});
		}
	});

	// Sort descending
	items.sort((a, b) => b.diameter - a.diameter);

	const sheets: CircleSheet[] = [];

	// Helper to check collision
	const isColliding = (
		c: PostedCircle,
		placed: PostedCircle[],
		sheetW: number,
		sheetH: number
	) => {
		// Wall bounds (center based)
		const r = c.diameter / 2;
		if (c.x - r < 0 || c.x + r > sheetW || c.y - r < 0 || c.y + r > sheetH)
			return true;

		for (const p of placed) {
			const distSq = (c.x - p.x) ** 2 + (c.y - p.y) ** 2;
			const rSum = c.diameter / 2 + p.diameter / 2 + gap;
			if (distSq < rSum * rSum - 0.001) return true; // epsilon
		}
		return false;
	};

	// Helper to generate candidates
	// Candidates are positions tangent to existing circles at hexagonal angles
	const getCandidates = (
		placed: PostedCircle[],
		r: number,
		sheetW: number,
		sheetH: number
	) => {
		const candidates: { x: number; y: number }[] = [];

		// Always try Bottom-Left corner
		candidates.push({ x: r + gap / 2, y: r + gap / 2 }); // Offset by radius + half gap to keep inside? logic above used 0-based bounds check?
		// Let's say (0,0) is board bottom-left.
		// If x-r < 0, it means x must be >= r.
		// So first candidate is at (r, r) (assuming 0 gap with wall, or add margin).
		// Let's add specific board padding if needed, but 'gap' is usually between parts.
		// Let's stick to simple: minimal x=r, y=r.

		if (placed.length === 0) return candidates;

		placed.forEach(p => {
			// For a new circle of radius r against existing P of radius R,
			// We want distance = r + R + gap
			const dist = p.diameter / 2 + r + gap;

			// Try placing around P at various angles.
			// Ideally we want to place 'touching' (gap distance) two other circles or one circle and wall.
			// Heuristic strategies:
			// 1. Tangent to P and Wall (X-axis)
			// 2. Tangent to P and Wall (Y-axis)
			// 3. Tangent to P and another P2

			// Simplified: Hexagonal candidates around P
			// Angles: 0, 60, 120, 180, 240, 300
			for (const angleStr of [0, 60, 120, 180, 240, 300]) {
				const angle = (angleStr * Math.PI) / 180;
				const cx = p.x + Math.cos(angle) * dist;
				const cy = p.y + Math.sin(angle) * dist;
				candidates.push({ x: cx, y: cy });
			}
		});

		// Filter out of bounds
		return candidates.filter(
			c =>
				c.x - r >= 0 && c.x + r <= sheetW && c.y - r >= 0 && c.y + r <= sheetH
		);
	};

	// Simple Grid-based approach for robustness fallback?
	// The "candidate points" approach is good but can be slow O(N^3) or fail to find "deep hole" slots if not careful.
	// For n=50-100 it's fine.

	// Improved Heuristic: "Front-Left" strategy (minimize Y then X)

	for (const item of items) {
		let placed = false;

		// Try fitting in existing sheets
		for (const sheet of sheets) {
			const r = item.diameter / 2;

			// Generate candidates
			// Candidate: (r, r) is always a simplified start if empty, but we have items.
			const candidates = getCandidates(sheet.circles, r, boardWidth, boardHeight);

			// Sort candidates by Y then X (Bottom-Left preference)
			candidates.sort((a, b) => {
				if (Math.abs(a.y - b.y) > 1e-5) return a.y - b.y;
				return a.x - b.x;
			});

			// Also consider "Tangent to two circles" calculation?
			// That calculates exact slots. The "60 degree" heuristic is an approx for uniform circles.
			// For mixed circles, we really should calculate intersection of "offset circles".
			// Let's stick to a simpler robust strategy:
			// PIXEL/GRID SEARCH is too slow.
			// Let's use the "Touching 2 items" generation.
			// For every pair A, B: calculate intersection points of circle(A, ra+r+gap) and circle(B, rb+r+gap).
			// Also pair A and Wall (x=0, y=0, x=W, y=H).

			// This is computationally heavier but accurate.
			// Let's try the simpler Candidate list first.
			// Actually, for "Optimized" users expect tight packing.
			// Let's refine the candidate generation to be "Vertex of the frontier".

			// REVISED STRATEGY for MVP Robustness + Quality:
			// 1. Generate candidate positions:
			//    - (r, r)
			//    - For each placed P:
			//      - (P.x + dist, P.y)  -- right
			//      - (P.x, P.y + dist)  -- top
			//      - (P.x + dx, P.y + dy) -- hex positions
			//    - For each pair P1, P2: Intersections of their extended boundaries.
			// 2. Filter invalid.
			// 3. Pick best.

			// Let's implement the Pair Intersection candidates for best density.
			// Candidates array
			const validCandidates: { x: number; y: number }[] = [];

			// Add "Corner" starts
			validCandidates.push({ x: r, y: r }); // Bottom-Left

			// Wall projections for each circle
			sheet.circles.forEach(c => {
				const dist = c.diameter / 2 + r + gap;
				// Against Left Wall (x=0) -> x=r. Y?
				// Intersection of x=r line and circle c?
				// (r - c.x)^2 + (y - c.y)^2 = dist^2
				// (y - c.y)^2 = dist^2 - (r - c.x)^2
				const dx = r - c.x;
				const dySq = dist * dist - dx * dx;
				if (dySq >= 0) {
					const dy = Math.sqrt(dySq);
					validCandidates.push({ x: r, y: c.y + dy }, { x: r, y: c.y - dy });
				}

				// Against Bottom Wall (y=0) -> y=r
				const dy_b = r - c.y;
				const dxSq = dist * dist - dy_b * dy_b;
				if (dxSq >= 0) {
					const dx = Math.sqrt(dxSq);
					validCandidates.push({ x: c.x + dx, y: r }, { x: c.x - dx, y: r });
				}

				// Single Circle Tangents (60deg, 90deg, 0deg) simply to help exploration
				validCandidates.push({ x: c.x + dist, y: c.y }); // Right
				validCandidates.push({ x: c.x, y: c.y + dist }); // Top
			});

			// Pair intersections
			for (let i = 0; i < sheet.circles.length; i++) {
				for (let j = i + 1; j < sheet.circles.length; j++) {
					const c1 = sheet.circles[i];
					const c2 = sheet.circles[j];
					const r1 = c1.diameter / 2 + r + gap;
					const r2 = c2.diameter / 2 + r + gap;

					// Intersection of two circles
					const d2 = (c1.x - c2.x) ** 2 + (c1.y - c2.y) ** 2;
					const d = Math.sqrt(d2);

					if (d > r1 + r2 || d < Math.abs(r1 - r2) || d === 0) continue;

					const a = (r1 * r1 - r2 * r2 + d2) / (2 * d);
					const h = Math.sqrt(Math.max(0, r1 * r1 - a * a));

					const x2 = c1.x + (a * (c2.x - c1.x)) / d;
					const y2 = c1.y + (a * (c2.y - c1.y)) / d;

					validCandidates.push(
						{
							x: x2 + (h * (c2.y - c1.y)) / d,
							y: y2 - (h * (c2.x - c1.x)) / d,
						},
						{ x: x2 - (h * (c2.y - c1.y)) / d, y: y2 + (h * (c2.x - c1.x)) / d }
					);
				}
			}

			// Sort candidates (Bottom-Left)
			validCandidates.sort((a, b) => {
				// Quantize Y slightly to prefer rows? No, pure bottom-left.
				// Actually pure Bottom is better (y ascending), then X.
				if (Math.abs(a.y - b.y) > 0.1) return a.y - b.y;
				return a.x - b.x;
			});

			// Find first valid
			for (const cand of validCandidates) {
				// Set temp pos
				item.x = cand.x;
				item.y = cand.y;
				if (!isColliding(item, sheet.circles, boardWidth, boardHeight)) {
					sheet.circles.push({ ...item }); // pushing copy
					placed = true;
					break;
				}
			}

			if (placed) break;
		}

		// If not placed, new sheet
		if (!placed) {
			const newSheet: CircleSheet = {
				width: boardWidth,
				height: boardHeight,
				circles: [],
				efficiency: 0,
			};
			// Place at first available slot (Bottom Left: r, r)
			const r = item.diameter / 2;
			// Check if it fits at all
			if (item.diameter <= Math.min(boardWidth, boardHeight)) {
				item.x = r; // + padding if global padding logic
				item.y = r;
				newSheet.circles.push({ ...item }); // copy
				sheets.push(newSheet);
			} else {
				console.warn(
					`Circle ${item.name} (D=${item.diameter}) too big for board`
				);
			}
		}
	}

	return sheets;
}
